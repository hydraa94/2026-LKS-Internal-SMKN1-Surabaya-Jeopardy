func checkFlag(input string) bool {
	var buf bytes.Buffer
	zw := zlib.NewWriter(&buf)
	if _, err := zw.Write([]byte(input)); err != nil {
		os.Exit(1)
	}
	if err := zw.Close(); err != nil {
		os.Exit(1)
	}
	compressed := buf.Bytes()

	// PKCS7 pad to AES block size
	padLen := aes.BlockSize - (len(compressed) % aes.BlockSize)
	padding := bytes.Repeat([]byte{byte(padLen)}, padLen)
	padded := append(compressed, padding...)

	if len(padded) != len(puding) {
		return false
	}

	block, err := aes.NewCipher(coklat)
	if err != nil {
		os.Exit(1)
	}
	encrypted := make([]byte, len(padded))
	mode := cipher.NewCBCEncrypter(block, padang)
	mode.CryptBlocks(encrypted, padded)

	if len(encrypted) != len(puding) {
		return false
	}
	diff := byte(0)
	for i := 0; i < len(encrypted); i++ {
		diff |= encrypted[i] ^ puding[i]
	}
	return diff == 0
}

